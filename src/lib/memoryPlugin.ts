/**
 * Per-agent memory injection, generated as a self-contained OpenCode file
 * plugin.
 *
 * `context.md` reaches every session through the global `instructions` list,
 * which is a compiled system prompt: it is added once, to everyone. A
 * teammate's own notes need the opposite: only that agent's sessions, primary
 * and subagent alike, and an edit should show up on the next call rather than
 * at the next compile. So this is a plugin registering the `context` hook,
 * which OpenCode runs before every model call with the request's system parts
 * and the agent it is for. The plugin reads `<root>/<agent-id>_context.md`
 * fresh from disk and pushes its text as one more system part.
 *
 * The memory root isn't knowable from inside the plugin (the config folder can
 * be anywhere), so it travels in the plugin entry's options.
 *
 * Installed at `~/.otto/agent-tool/otto-memory/{package.json,index.js}` and
 * added to the machine's global config as one
 * `{ package: "file://…", options: { root } }` entry. It may only import
 * `node:*` and `@opencode/plugin`.
 */
import type { OpenCode } from "./opencode/client";
import { readHome, toolPackageJson, toolPluginDir, toolPluginInstalled, toolPluginOptions, withToolPlugin, withoutToolPlugin, writeIfChanged } from "./agentTools";
import { readGlobalConfig, updateGlobalConfig, type GlobalConfig } from "./opencode/config";

export const MEMORY_PLUGIN_ID = "otto.memory";
/** The folder's name, as `agentTools` sees it. */
export const MEMORY_PLUGIN_NAME = "otto-memory";
export const MEMORY_PLUGIN_FILE = "index.js";
/** A teammate's own injected file: `<agent-id>_context.md` at the memory root. */
export const AGENT_CONTEXT_SUFFIX = "_context.md";

export function memoryPluginDir(home: string): string {
  return toolPluginDir(home, MEMORY_PLUGIN_NAME);
}

export function memoryPluginPackageJson(): string {
  return toolPackageJson(MEMORY_PLUGIN_NAME);
}

/** One entry, pointing at the installed folder, carrying the memory root. */
export function withAgentMemoryPlugin(cfg: GlobalConfig, dir: string, root: string): GlobalConfig {
  return withToolPlugin(cfg, dir, MEMORY_PLUGIN_NAME, { root });
}

/** Drops every copy, including an old entry under the v1 `plugin` key. */
export function withoutAgentMemoryPlugin(cfg: GlobalConfig): GlobalConfig {
  return withoutToolPlugin(cfg, MEMORY_PLUGIN_NAME);
}

/** Installed exactly once, at this folder, with this memory root. */
export function agentMemoryPluginInstalled(cfg: GlobalConfig, dir: string, root: string): boolean {
  return toolPluginInstalled(cfg, dir, MEMORY_PLUGIN_NAME) && toolPluginOptions(cfg, MEMORY_PLUGIN_NAME)?.root === root;
}

let source: string | null = null;
/** The generated `index.js` (the same text on every machine). */
export function memoryPluginSource(): string {
  source ??= RUNTIME;
  return source;
}

const installed = new WeakMap<OpenCode, { root: string; pending: Promise<string> }>();

/**
 * Write the plugin and add exactly one config entry, remembering the memory
 * root it was installed for. Cached per connection, so a reconnect doesn't
 * rewrite the same files; a failed attempt leaves no entry, so the next one
 * tries again.
 */
export function ensureMemoryPlugin(client: OpenCode, root: string): Promise<string> {
  const hit = installed.get(client);
  if (hit && hit.root === root) return hit.pending;
  const pending = (async () => {
    const dir = memoryPluginDir(await readHome(client));
    await writeIfChanged(client, `${dir}/package.json`, memoryPluginPackageJson());
    await writeIfChanged(client, `${dir}/${MEMORY_PLUGIN_FILE}`, memoryPluginSource());
    // The root moves when the config folder does, and the plugin would read a
    // folder nobody writes to, so an entry for another root counts as missing.
    if (!agentMemoryPluginInstalled(await readGlobalConfig(client), dir, root)) {
      await updateGlobalConfig(client, (cfg) => withAgentMemoryPlugin(cfg, dir, root));
    }
    return dir;
  })();
  installed.set(client, { root, pending });
  pending.catch(() => {
    if (installed.get(client)?.pending === pending) installed.delete(client);
  });
  return pending;
}

/** Stop injecting: drop the config entry. The files and every note stay. */
export async function removeMemoryPlugin(client: OpenCode): Promise<void> {
  installed.delete(client);
  await updateGlobalConfig(client, withoutAgentMemoryPlugin);
}

const RUNTIME = `// Generated by Otto. Do not edit: Otto writes this file from src/lib/memoryPlugin.ts.
//
// Every model call gets this agent's own notes, \`<root>/<agent-id>_context.md\`,
// read from disk each time: an edit lands on the next call, and a subagent
// reads its own file, never the one of the teammate that handed it work.
// The memory root comes in as the plugin entry's options.

import { Plugin } from "@opencode/plugin";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

export const AGENT_CONTEXT_SUFFIX = "_context.md";
export const HEADING = "# Your notes";

/** \`<root>/<agent>_context.md\`, or null when the id isn't a plain agent id. */
export function agentContextPath(root, agent) {
  const id = typeof agent === "string" ? agent.trim() : "";
  // Letters, digits, dot, dash and underscore; never something that leads with a dot.
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id)) return null;
  return join(root, id + AGENT_CONTEXT_SUFFIX);
}

/** The agent's notes, trimmed. Null when there is no file, it is empty, or it can't be read. */
export async function readAgentContext(root, agent) {
  const path = agentContextPath(root, agent);
  if (!path) return null;
  try {
    const text = (await readFile(path, "utf8")).trim();
    return text || null;
  } catch {
    return null;
  }
}

/** What the model sees: a short heading, where the file is, then the notes. */
export function notesPart(path, text) {
  return { type: "text", text: HEADING + "\\nKept in \`" + path + "\`. Edit that file to change what you carry.\\n\\n" + text };
}

export default Plugin.define({
  id: "otto.memory",
  async setup(ctx) {
    const root = ctx.options && typeof ctx.options.root === "string" ? ctx.options.root.trim() : "";
    // An entry with no root has nothing to read; stay quiet rather than fail the call.
    if (!root) return;
    await ctx.session.hook("context", async (event) => {
      if (!event || !Array.isArray(event.system)) return;
      const path = agentContextPath(root, event.agent);
      if (!path) return;
      const text = await readAgentContext(root, event.agent);
      if (!text) return;
      const part = notesPart(path, text);
      // One copy per request: a hook that runs twice on one request must not repeat the notes.
      if (event.system.some((p) => p && p.text === part.text)) return;
      event.system.push(part);
    });
  },
});
`;
