/**
 * The agent-facing `present` tool: the one way an agent shows the user
 * something — a file in the workspace, an http(s) URL, or raw HTML — instead
 * of describing it.
 *
 * Generated as a self-contained OpenCode file plugin for the same reason the
 * schedule tool is (see `schedulesPlugin.ts`): it runs inside OpenCode on the
 * agent machine, where Otto's source isn't installed, so it may only import
 * `@opencode/plugin`. It is deliberately dumb: it validates the shape of the
 * call and hands the call back as a receipt. Otto's app reads the tool call
 * from the session and decides what to draw (see `lib/artifacts.ts`), so the
 * renderers, the path check and the URL rules live in one place.
 *
 * Installed at `~/.otto/agent-tool/otto-present/{package.json,index.js}` and
 * added to the machine's global config as one `{ package: "file://…" }` entry.
 */
import type { OpenCode } from "./opencode/client";
import { readHome, toolPackageJson, toolPluginDir, toolPluginInstalled, withToolPlugin, withoutToolPlugin, writeIfChanged } from "./agentTools";
import { readGlobalConfig, updateGlobalConfig, type GlobalConfig } from "./opencode/config";

export const PRESENT_PLUGIN_ID = "otto.present";
/** The folder's name, as `agentTools` sees it, and the tool the agent calls. */
export const PRESENT_PLUGIN_NAME = "otto-present";
export const PRESENT_PLUGIN_FILE = "index.js";
export const PRESENT_TOOL = "present";

export function withPresentPlugin(cfg: GlobalConfig, dir: string): GlobalConfig {
  return withToolPlugin(cfg, dir, PRESENT_PLUGIN_NAME);
}

export function withoutPresentPlugin(cfg: GlobalConfig): GlobalConfig {
  return withoutToolPlugin(cfg, PRESENT_PLUGIN_NAME);
}

export function presentPluginInstalled(cfg: GlobalConfig, dir: string): boolean {
  return toolPluginInstalled(cfg, dir, PRESENT_PLUGIN_NAME);
}

export function presentPluginDir(home: string): string {
  return toolPluginDir(home, PRESENT_PLUGIN_NAME);
}

export function presentPluginPackageJson(): string {
  return toolPackageJson(PRESENT_PLUGIN_NAME);
}

let source: string | null = null;
/** The generated `index.js` (the same text on every machine). */
export function presentPluginSource(): string {
  source ??= RUNTIME;
  return source;
}

const installed = new WeakMap<OpenCode, Promise<string>>();

/**
 * Write the plugin and add exactly one config entry. Cached per connection, so
 * a reconnect doesn't rewrite the same files; a failed attempt leaves no
 * entry, so the next connection tries again.
 */
export function ensurePresentPlugin(client: OpenCode): Promise<string> {
  const hit = installed.get(client);
  if (hit) return hit;
  const pending = (async () => {
    const dir = presentPluginDir(await readHome(client));
    await writeIfChanged(client, `${dir}/package.json`, presentPluginPackageJson());
    await writeIfChanged(client, `${dir}/${PRESENT_PLUGIN_FILE}`, presentPluginSource());
    if (!presentPluginInstalled(await readGlobalConfig(client), dir)) {
      await updateGlobalConfig(client, (cfg) => withPresentPlugin(cfg, dir));
    }
    return dir;
  })();
  installed.set(client, pending);
  pending.catch(() => installed.delete(client));
  return pending;
}

/** Stop offering the tool: drop the config entry. The files stay. */
export async function removePresentPlugin(client: OpenCode): Promise<void> {
  installed.delete(client);
  await updateGlobalConfig(client, withoutPresentPlugin);
}

const RUNTIME = `// Generated by Otto. Do not edit: Otto writes this file from src/lib/presentPlugin.ts.
//
// The agent's one way to show the user something. The call is a receipt: Otto
// reads it from the session and draws the artifact beside the chat.
import { Plugin } from "@opencode/plugin";

export const TOOL_SCHEMA = {
  type: "object",
  properties: {
    source: {
      type: "string",
      description:
        "What to show: a path in this workspace (e.g. out/cover.png, app/index.html), an http(s) URL (e.g. https://example.com, localhost:5173), or raw HTML.",
    },
    title: { type: "string", description: "A short label the user will recognise, shown on the chip and in the panel (e.g. Landing page, Signups by week)." },
    as: {
      type: "string",
      enum: ["image", "html", "url", "text", "download"],
      description: "Force a renderer. Leave it out: the source and its extension are enough.",
    },
  },
  required: ["source"],
  additionalProperties: false,
};

export const KINDS = ["image", "html", "url", "text", "download"];
// Kept in step with MAX_SOURCE in src/lib/artifacts.ts: past this the app
// refuses the entry, so the tool refuses the call first and says why.
export const MAX_SOURCE = 512000;
export const MAX_TITLE = 160;

/** Check the call's shape. Throws with something the model can act on. */
export function normalizePresent(input) {
  const raw = input && input.source;
  const source = typeof raw === "string" ? raw.trim() : "";
  if (!source) throw new Error("source is required: a path in the workspace, an http(s) URL, or HTML.");
  if (source.length > MAX_SOURCE) {
    throw new Error("source is too big (over " + MAX_SOURCE + " characters). Write it to a file and present the file instead.");
  }
  const out = { source };
  if (typeof input.title === "string" && input.title.trim()) out.title = input.title.trim().slice(0, MAX_TITLE);
  if (KINDS.includes(input.as)) out.as = input.as;
  return out;
}

/** What the model sees back: a receipt, with markup cut so it can't echo a page. */
export function receipt(call) {
  const source = call.source.length > 200 ? call.source.slice(0, 200) + "…" : call.source;
  return { presented: true, source, title: call.title, as: call.as };
}

function makeTool() {
  return {
    name: "present",
    description:
      "Show the user something, full size, in Otto's panel beside the chat, with a chip in the chat they can click to open it again. Source: a file in this workspace, an http(s) URL (a dev server on localhost works), or a small piece of raw HTML. Use it whenever the user should see what you made rather than read about it: a page or app you built or changed, a screenshot, a chart, an image, a PDF or report, a document you wrote. Present it once, when it's ready and you've checked it renders; present again only after a real change. Give it a short title the user will recognise. For anything bigger than a snippet, write a file and present the file. Don't use it for code diffs, logs or command output. What it is (image, page, text, download) is worked out from the path or URL; set \`as\` only to override that. Paths outside the workspace aren't shown.",
    input: TOOL_SCHEMA,
    options: { codemode: false },
    execute: async (input) => {
      let call;
      try {
        call = normalizePresent(input);
      } catch (e) {
        return { content: JSON.stringify({ presented: false, error: (e && e.message) || String(e) }) };
      }
      return {
        content: JSON.stringify({ ...receipt(call), note: "Shown to the user: a chip in the chat opens it in the panel. Tell them in a sentence what to look at." }),
        // Only the keys that are set: OpenCode never settles a call whose
        // metadata holds an undefined value, so the turn would hang on it.
        metadata: { ...call },
      };
    },
  };
}

export default Plugin.define({
  id: "otto.present",
  async setup(ctx) {
    await ctx.tool.transform((editor) => {
      editor.add(makeTool());
    });
  },
});
`;
